// درست‌نویسی فارسی با کد، نه با مدل: این غلط‌ها فقط یه جواب درست دارن، پس کد همون جواب رو
// فوری، رایگان و هر بار یکسان می‌ده. قاعده‌ی طلایی: یه اصلاح غلط از اصلاح‌نکردن بدتره؛ فقط چیزی
// عوض می‌شه که مطمئنیم غلطه. بدون server-only و بدون import، تا صفحه‌ی ویراستار توی مرورگر و
// node توی تست بتونن اجراش کنن.

const ZWNJ = "\u200C";

// حرف فارسی، به‌صورت فهرست صریح: \b و \w توی regex جاوااسکریپت فقط A–Z و 0–9 رو می‌شناسن، و
// \p{Script=Arabic} رقم‌های فارسی رو هم می‌گیره. اعراب (ً تا ْ) هم حرف حساب می‌شن تا «واقعاً?»
// به «واقعاً؟» برسه. به ترتیب: ء تا غ، ف تا ي با اعراب، پ چ ژ ک گ ی.
const LETTER = "\u0621-\u063A\u0641-\u0652\u067E\u0686\u0698\u06A9\u06AF\u06CC";

// جای هر توکن لاتین یه «object replacement character» می‌ذاریم: نه حرفه، نه رقم، نه فاصله، پس
// هیچ قاعده‌ای بهش نمی‌چسبه.
const KEPT = "\uFFFC";

// توکن لاتین: هر تکه‌ی بین فاصله‌ها که حرف لاتین، @ یا :// داره (4K، S24، لینک، ایمیل). یه
// کاراکتر عوض‌شده توی لینک یعنی یه لینک دیگه، پس این توکن‌ها اصلاً دست نمی‌خورن، حتی «ي» یا
// «ك» داخلشون. توکنی که خودش KEPT داره هم نگه داشته می‌شه، تا هر KEPT توی خط یه جانشین باشه.
const KEPT_TOKEN = /[A-Za-z@\uFFFC]|:\/\//;

const PERSIAN_MARK: Record<string, string> = { "?": "؟", ",": "،", ";": "؛" };

// علامتی که پیش از اون (بدون فاصله‌ها و علامت‌های همون دنباله) حرف فارسی باشه: «چی ?» و «واقعا??».
// ویرگول وسط عدد (۱,۰۰۰) و علامت بعد از توکن لاتین دست نمی‌خورن.
const MARK_AFTER_LETTER = new RegExp(`(?<=[${LETTER}][ ?,;؟،؛!]*)[?,;]`, "g");

// «می» و «نمی» فقط وقتی جدا نوشته شدن و بعدشون کلمه‌ی فارسی میاد. توی «میخواهم» نیم‌فاصله
// نمی‌ذاریم، چون «میز» و «میوه» هم با «می» شروع می‌شن و کد نمی‌تونه فرقشون رو بفهمه.
const SEPARATE_MI = new RegExp(`(?<=^| )(ن?می) (?=[${LETTER}])`, "g");

// «های» و «هایی» جدا بعد از کلمه‌ای که به حرف فارسی تموم می‌شه. «ها»ی تنها دست نمی‌خوره: توی
// «یادت نره ها» حرف تأکیده، نه نشانه‌ی جمع.
const SEPARATE_HA = new RegExp(`(?<=[${LETTER}]) (هایی?)(?= |$)`, "g");

/**
 * Fixes Persian spelling that has one right answer: Arabic ي/ك, the ezafe after «ه», separate
 * «می»/«های», broken ZWNJs, extra spaces and Latin ?,; after Persian words. Digits, Latin words,
 * links and emails stay exactly as they are, correct text comes back unchanged, and
 * normalize(normalize(x)) === normalize(x).
 */
export function normalize(text: string): string {
  // هر خط جدا؛ شکست خط‌ها و خط‌های خالی هیچ‌وقت با این الگو جور نمی‌شن، پس دقیقاً می‌مونن.
  return text.replace(/[^\r\n]+/g, normalizeLine);
}

// ترتیب قدم‌ها مهمه: هر قدم متنی رو آماده می‌کنه که قدم بعدی دنبالشه، و هیچ قدمی کار قدم
// قبلی رو خراب نمی‌کنه. برای همین یه بار اجرا کافیه و اجرای دوم چیزی رو عوض نمی‌کنه.
function normalizeLine(line: string): string {
  // ۱. توکن‌های لاتین اول کنار می‌رن تا هیچ قدم بعدی بهشون نرسه.
  const kept: string[] = [];
  let s = line.replace(/[^ \t]+/g, (token) => {
    if (!KEPT_TOKEN.test(token)) return token;
    kept.push(token);
    return KEPT;
  });

  // ۲. حرف‌ها، قبل از بقیه: قدم‌های بعدی دنبال «ی» و «ه» می‌گردن، پس «خانه ي من» فقط بعد از
  // این قدم یه «ی» جدا داره که بشه چسبوندش. رقم‌ها عمداً دست نمی‌خورن (تصمیم تیم): زمان
  // زیرنویس، فصل یوتیوب و هشتگ با همون رقم‌ها کار می‌کنن، و فارسی نشون دادن عدد کار نمایشه.
  s = s
    .replace(/[\u064A\u0649]/g, "ی")
    .replace(/\u0643/g, "ک")
    .replace(/\u0647\u0654|\u06C0/g, `ه${ZWNJ}ی`);

  // ۳. فاصله و نیم‌فاصله، قبل از علامت‌ها و چسبوندن: اون‌ها دنبال دقیقاً یه فاصله و حرف آخر
  // واقعی کلمه‌ان، پس «کتاب‌ های» فقط بعد از پاک شدن نیم‌فاصله‌ی خراب «کتاب‌های» می‌شه.
  // داخل همین قدم هم اول نیم‌فاصله‌ی خراب پاک می‌شه و بعد فاصله‌ها یکی می‌شن، چون پاک شدن
  // نیم‌فاصله‌ی بین دو فاصله دو تا فاصله‌ی کنار هم جا می‌ذاره.
  s = s
    .replace(/\u200C+/g, ZWNJ)
    .replace(/(?<=^|[ \t]|\p{P})\u200C|\u200C(?=$|[ \t]|\p{P})/gu, "")
    .replace(/[ \t]+/g, " ")
    .replace(/^ | $/g, "");

  // ۴. علامت‌ها، قبل از چسبوندن: فاصله‌ی بعد از علامت ممکنه یه «می» جدا بسازه، مثل
  // «سلام،می خواهم» ← «سلام، می خواهم»، که قدم ۵ درستش می‌کنه. بعد از ؟ ، ؛ یه فاصله میاد،
  // جز بین دو رقم: «۲،۵۰۰» یه عدده، نه یه فهرست.
  s = s
    .replace(MARK_AFTER_LETTER, (mark) => PERSIAN_MARK[mark])
    .replace(/ (?=[؟،؛])/g, "")
    .replace(/[؟،؛](?=[\p{L}«(])|(?<!\p{N})[؟،؛](?=\p{N})/gu, "$& ");

  // ۵. چسبوندن با نیم‌فاصله، آخر از همه: نیم‌فاصله فقط بین دو حرف میاد و هیچ قدمی برش نمی‌داره.
  s = s
    .replace(/(?<=ه) ی(?= |$)/g, `${ZWNJ}ی`)
    .replace(SEPARATE_MI, `$1${ZWNJ}`)
    .replace(SEPARATE_HA, `${ZWNJ}$1`);

  // ۶. توکن‌های لاتین به همون ترتیب و دست‌نخورده برمی‌گردن.
  let next = 0;
  return s.replace(/\uFFFC/g, () => kept[next++]);
}
